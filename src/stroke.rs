/// Width of one glyph in the same grid units as [`strokes`].
pub fn advance(ch: char) -> f32 {
    match ch {
        ' ' => 4.2,
        'i' | 'l' | 'I' | '.' | ':' | '1' => 4.8,
        'f' | 'j' | 't' => 5.4,
        'm' | 'w' | 'M' | 'W' => 8.6,
        _ => 7.6,
    }
}
